// 任务周期 [ns] → 控制周期 [s], 下限 1us
static float DtSecFromCycleNS(ULONG cycleNS)
{
    float dt = (float)cycleNS * 1.0e-9f;
    if ((dt < 1.0e-6f) || (dt != dt)) {
        dt = 1.0e-6f;
    }
    return dt;
}

// 目标位置 [指令单位] 四舍五入到 LONG, 并限制在 int32 可用范围内
// @param pos 目标位置 (double, 绝对位置可能是 2^31 量级) [指令单位]
// @return 目标位置 [指令单位]
// ★ 钳位值 MUST 与 FEED_POS_LIMIT_UNIT 一致 (送纸凸轮那边按同一上限判跳闸),
//   原来写死 2e9: 绝对位置一旦越过 2e9, 607Ah 就被钉死, 表现为"电机不动、
//   转矩 1%、驱动器不报错、程序侧跟随偏差发散" —— 2026-11-23 实机踩过。
static LONG PosToLong(double pos)
{
    double p = (pos >= 0.0) ? (pos + 0.5) : (pos - 0.5);
    if (p >  FEED_POS_LIMIT_UNIT) p =  FEED_POS_LIMIT_UNIT;
    if (p < -FEED_POS_LIMIT_UNIT) p = -FEED_POS_LIMIT_UNIT;
    return (LONG)p;
}

// 驱动侧 CiA402 模式号: CSV(9) / CST(10) / CSP(8)
// @param driveMode SpeedTestSequencer::DriveMode
// @return 6060h 模式号
static SHORT DriveModeCode(uint8_t driveMode)
{
    if (driveMode == SpeedTestSequencer::DRIVE_CST) {
        return 10;
    }
    if (driveMode == SpeedTestSequencer::DRIVE_CSP) {
        return 8;
    }
    return 9;
}

// 电机规格 → 伺服 Params (XAE/PLC 可在数据区覆盖)
// @param pServo 该槽位伺服
// @param ucMotor MOTOR_xxx 编号 (MotorSpec.h)
static void FillServoParams(ServoIO* pServo, unsigned char ucMotor)
{
	if (pServo == NULL) {
		return;
	}
	const MOTOR_SPEC_T* pSpec = MotorSpecGet(ucMotor);
	pServo->Params.EncCntPerRev = pSpec->ulEncCntPerRev;
	pServo->Params.GearNum      = pSpec->ulGearNum;
	pServo->Params.GearDen      = pSpec->ulGearDen;
	pServo->Params.InertiaBase  = pSpec->fInertiaBase;
	pServo->Params.RatedTorque  = pSpec->fRatedTorque;
}

