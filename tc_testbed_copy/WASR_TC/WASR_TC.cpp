// PREOP → SAFEOP
HRESULT CWASR_TC::SetObjStatePS(PTComInitDataHdr pInitData)
{
	// 数据区: Inputs(0) / Outputs(1) / Servos(2) / Status(3)
	m_Trace.Log(tlVerbose, FENTERA_STR());
	HRESULT hr = S_OK;
	IMPLEMENT_ITCOMOBJECT_EVALUATE_INITDATA(pInitData);

	// CoE SDO 工具: 这里只把 TCom 服务器指针交给它, 不建 ADS 端口。
	// 端口在第一次真正的 SDO 读写之后由 CycleUpdate 的 Poll() 懒建。
	m_coeSdo.SetServer(m_spSrv);

	// 驱动器监视: 重新开始计时 (上一个 OP 周期的在飞请求已在 SP 里清掉)
	m_drvMonTick = 0;
	m_drvMonRatioReq[0] = 0;
	m_drvMonRatioReq[1] = 0;
	m_drvMonRigReq[0] = 0;
	m_drvMonRigReq[1] = 0;
	m_drvMonRatioGot[0] = FALSE;
	m_drvMonRatioGot[1] = FALSE;
	m_drvMonRigGot[0] = FALSE;
	m_drvMonRigGot[1] = FALSE;
	// 重新进入 OP 时按当前 ExperimentType 再写一次 Sig* 初值
	m_lastExperimentType = -1;

	// 先按 125us 初始化, 首周期再按实际任务周期重算
	InitControl(m_dtSec);
	m_counter = 0;
	m_cia402Step = 0;
	m_cia402StepLoad = 0;
	m_prevEnable = 0;

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// 初始化控制层 (速度换算 / 实验序列器)
// @param dtSec 控制周期 [s]
///////////////////////////////////////////////////////////////////////////////
void CWASR_TC::InitControl(float dtSec)
{
	m_dtSec = dtSec;

	// 驱动侧伺服 (指针无效时回退 Servo0)
	ServoIO* d = m_Servos.DriveSide;
	if (d == NULL) {
		d = &m_Servos.Servo0;
		m_Servos.DriveSide = d;
	}

	// 每台伺服各自的 [rpm] ← (指令单位/s) 换算系数
	//   电机轴每转指令单位数 = 编码器每转计数 × 齿轮比分母 / 分子
	for (int i = 0; i < 2; i++) {
		ServoIO* s = (i == 0) ? &m_Servos.Servo0 : &m_Servos.Servo1;
		ULONG encCnt = s->Params.EncCntPerRev;
		if (encCnt == 0) {
			encCnt = 131072;
		}
		ULONG gearNum = s->Params.GearNum;
		ULONG gearDen = s->Params.GearDen;
		if (gearNum == 0) gearNum = 1;
		if (gearDen == 0) gearDen = 1;
		float unitsPerRev = (float)encCnt * (float)gearDen / (float)gearNum;
		if (unitsPerRev < 1.0f) unitsPerRev = 1.0f;
		m_speedScaleServo[i] = 60.0f / unitsPerRev;
		// 位置差分测速: wrap modulus = 每转指令单位数,
		// gain = (指令单位/拍) → rpm = 60 / (每转指令单位数 × dtSec)
		m_encFilter[i].Init(0, (LONG)unitsPerRev, m_speedScaleServo[i] / m_dtSec);
	}

	// 驱动侧那台的换算系数 (CSV 速度指令 / 606Ch 反馈)
	{
		int di = (d == &m_Servos.Servo1) ? 1 : 0;
		m_speedScale = m_speedScaleServo[di];
		// 送纸凸轮: mm→指令单位 = 每转指令单位数 (= 60 / m_speedScaleServo[di])
		//           / 电机每转工艺 mm (g_cfgFeed.fMmPerMotorRev)
		if (g_cfgFeed.fMmPerMotorRev > 0.0) {
			m_testSeq.feedMmToUnit = 60.0 / (double)m_speedScaleServo[di] / g_cfgFeed.fMmPerMotorRev;
		}
	}

	// 实验序列器: 总惯量 = 转子惯量 × (1 + 惯量比/100), 供转矩扫频速度环折算
	float iner = d->Params.InertiaBase;
	if (iner <= 0.0f) {
		iner = 1.0e-5f;
	}
	// 惯量比 [%] = 驱动侧那台伺服的实测值 (SDO 监视, 原始值 0.01 直接就是百分数)
	float ratio = (float)m_Status.Driver_Inertia_ratio;
	float totalIner = iner * (1.0f + ratio / 100.0f);
	m_testSeq.Init(m_dtSec, totalIner, d->Params.RatedTorque, (float)WASR_TC_TORLIM);
}

///////////////////////////////////////////////////////////////////////////////
// 驱动器监视: 每 IR_MON_PERIOD_MS 读一次两台伺服的惯量比与刚性等级
//
// 对象 (原始值):
//   Servo0 = 维控 VD5L  0x2003:01 惯量比 (0.01, 100..10000) / 0x2003:02 刚性 (0..31)
//   Servo1 = 汇川       0x2008:10 惯量比 (0.01, 0..12000)    / 0x2009:02 刚性 (0..41)
// 只读不写: SDO upload 不磨损 EEPROM。驱动侧那台的值由 CycleUpdate 镜像到 Status。
// 每台每个对象最多一个在飞请求 (超时没回来也不叠加), 4 个请求不会占满请求表。
///////////////////////////////////////////////////////////////////////////////
void CWASR_TC::DriverMonitorRun()
{
#if IR_MON_ENABLE
	float periodF;
	ULONG period;
	int   i;

	// 监视周期 [ms] → 控制周期数 (四舍五入, 至少 1 拍)
	periodF = ((float)IR_MON_PERIOD_MS * 0.001f) / m_dtSec;
	period = (periodF >= 1.0f) ? (ULONG)(periodF + 0.5f) : 1UL;

	m_drvMonTick++;
	if (m_drvMonTick < period) {
		return;
	}
	m_drvMonTick = 0;

	for (i = 0; i < 2; i++) {
		// 该伺服的惯量比对象与有效原始值范围
		USHORT iIdx = (i == 0) ? (USHORT)IR_MON_S0_INDEX : (USHORT)IR_MON_S1_INDEX;
		UCHAR  iSub = (i == 0) ? (UCHAR)IR_MON_S0_SUBINDEX : (UCHAR)IR_MON_S1_SUBINDEX;
		ULONG  iMin = (i == 0) ? (ULONG)IR_MON_S0_VAL_MIN : (ULONG)IR_MON_S1_VAL_MIN;
		ULONG  iMax = (i == 0) ? (ULONG)IR_MON_S0_VAL_MAX : (ULONG)IR_MON_S1_VAL_MAX;
		// 该伺服的刚性等级对象与有效原始值范围
		USHORT rIdx = (i == 0) ? (USHORT)IR_MON_S0_RIG_INDEX : (USHORT)IR_MON_S1_RIG_INDEX;
		UCHAR  rSub = (i == 0) ? (UCHAR)IR_MON_S0_RIG_SUBINDEX : (UCHAR)IR_MON_S1_RIG_SUBINDEX;
		ULONG  rMin = (i == 0) ? (ULONG)IR_MON_S0_RIG_VAL_MIN : (ULONG)IR_MON_S1_RIG_VAL_MIN;
		ULONG  rMax = (i == 0) ? (ULONG)IR_MON_S0_RIG_VAL_MAX : (ULONG)IR_MON_S1_RIG_VAL_MAX;

		// 1) 收惯量比结果 (没完成就等, 不叠加新请求)
		if (m_drvMonRatioReq[i] != 0) {
			CoeSdoResult r;
			if (m_coeSdo.GetResult(m_drvMonRatioReq[i], &r)) {
				m_drvMonRatioReq[i] = 0;
				if (r.Status == COE_SDO_OK) {
					if (r.Value >= iMin && r.Value <= iMax) {
						// 原始值 = 惯量比 [%] (单位 0.01)
						m_drvMonRatio[i] = (USHORT)r.Value;
						if (!m_drvMonRatioGot[i]) {
							m_drvMonRatioGot[i] = TRUE;
							m_Trace.Log(tlAlways,
								"WASR_TC: driver monitor Servo%d inertia ratio = %.2f%% (0x%04X:%02X)",
								i, (double)m_drvMonRatio[i], (unsigned)iIdx, (unsigned)iSub);
						}
					} else {
						m_Trace.Log(tlVerbose,
							"WASR_TC: driver monitor Servo%d inertia raw %u out of %u..%u, keep old",
							i, (unsigned)r.Value, (unsigned)iMin, (unsigned)iMax);
					}
				}
			}
		}

		// 2) 收刚性等级结果
		if (m_drvMonRigReq[i] != 0) {
			CoeSdoResult r;
			if (m_coeSdo.GetResult(m_drvMonRigReq[i], &r)) {
				m_drvMonRigReq[i] = 0;
				if (r.Status == COE_SDO_OK) {
					if (r.Value >= rMin && r.Value <= rMax) {
						m_drvMonRig[i] = (USHORT)r.Value;
						if (!m_drvMonRigGot[i]) {
							m_drvMonRigGot[i] = TRUE;
							m_Trace.Log(tlAlways,
								"WASR_TC: driver monitor Servo%d rigidity level = %u (0x%04X:%02X)",
								i, (unsigned)m_drvMonRig[i], (unsigned)rIdx, (unsigned)rSub);
						}
					} else {
						m_Trace.Log(tlVerbose,
							"WASR_TC: driver monitor Servo%d rigidity raw %u out of %u..%u, keep old",
							i, (unsigned)r.Value, (unsigned)rMin, (unsigned)rMax);
					}
				}
			}
		}

		// 3) 没有在飞请求就发下一次读
		if (m_drvMonRatioReq[i] == 0) {
			m_drvMonRatioReq[i] = m_coeSdo.Read(i, iIdx, iSub, 2);
		}
		if (m_drvMonRigReq[i] == 0) {
			m_drvMonRigReq[i] = m_coeSdo.Read(i, rIdx, rSub, 2);
		}
	}
#endif
}

///////////////////////////////////////////////////////////////////////////////
// 按实验类型写入 SigFreq / SigAmp / SigOffset 初值
// 只在程序启动与用户切换 ExperimentType 时调用; 之后用户可随意调整
// @param type 当前实验类型
///////////////////////////////////////////////////////////////////////////////
void CWASR_TC::ApplyExperimentDefaults(ExperimentType_T type)
{
	// 频率 [Hz]
	float freq = 0.0f;
	// 幅值 (单位随实验)
	float amp = 0.0f;
	// 偏置 (单位随实验)
	float off = 0.0f;

	switch (type) {
	case ExperimentType_StepResponse:
		// 阶跃: 中心速度 ± 幅值 [rpm]
		amp = STEP_TEST_AMP_SPD;
		off = STEP_TEST_BASE_SPD;
		break;

	case ExperimentType_WaveResponse:
		// 定频波形: 基础速度 + 幅值 [rpm], 频率 [Hz]
		freq = WAVE_TEST_FREQ;
		amp  = WAVE_TEST_AMPLITUDE;
		off  = WAVE_TEST_BASE_SPD;
		break;

	case ExperimentType_VelocitySweep:
		// 速度扫频: 频率是回读, 幅值 [rpm] / 基础速度 [rpm]
		amp = SWEEP_TEST_AMPLITUDE;
		off = SWEEP_TEST_BASE_SPD;
		break;

	case ExperimentType_TorqueSweep:
		// 转矩扫频: 频率是回读, 幅值 [0.1% 额定] / 基础速度 [rpm]
		amp = TOR_SWEEP_TEST_AMPLITUDE;
		off = TOR_SWEEP_TEST_BASE_SPD;
		break;

	case ExperimentType_LoadDisturbScan:
		// 负载扫描: 频率/幅度都是回读, 偏置是负载侧基准转矩 [0.1% 额定]
		break;

	case ExperimentType_PosLoopWave:
		// 位置环波形: 原点/幅值 [指令单位], 频率 [Hz]
		freq = POSWAVE_TEST_FREQ;
		amp  = POSWAVE_TEST_AMPLITUDE;
		off  = (float)POSWAVE_TEST_ORIGIN;
		break;

	case ExperimentType_VelocityClosedLoopPRBS:
		// 速度闭环 PRBS: 频率是分析带半宽 [Hz] (带 = 0~2×), 幅值/基础速度 [rpm]
		freq = PRBS_TEST_FREQ;
		amp  = PRBS_TEST_AMPLITUDE;
		off  = PRBS_TEST_BASE_SPD;
		break;

	case ExperimentType_FeedCamTest:
		// 送纸凸轮: SigOffset = 主轴线速度 [m/min] (默认 30 慢速首测),
		// SigAmp = Start 触发线 (0, 0→1 上升沿送一次), SigFreq 回读凸轮相位
		off = 30.0f;
		break;

	case ExperimentType_Manual:
	default:
		// 不启动实验, 三个量不用
		break;
	}

	m_Status.SigFreq   = freq;
	m_Status.SigAmp    = amp;
	m_Status.SigOffset = off;
}

///////////////////////////////////////////////////////////////////////////////
// SAFEOP → OP
HRESULT CWASR_TC::SetObjStateSO()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());
	HRESULT hr = S_OK;

	hr = FAILED(hr) ? hr : AddModuleToCaller();

	if ( FAILED(hr) )
	{
		RemoveModuleFromCaller();
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

