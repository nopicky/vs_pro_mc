// 任务周期 [ns] → 控制周期 [s], 下限 1us
static float DtSecFromCycleNS(ULONG cycleNS)
{
    float dt = (float)cycleNS * 1.0e-9f;
    if ((dt < 1.0e-6f) || (dt != dt)) {
        dt = 1.0e-6f;
    }
    return dt;
}

// 目标位置 [指令单位] 四舍五入到 LONG, 并限制在 int32 可用范围内
// @param pos 目标位置 (double, 绝对位置可能是 2^31 量级) [指令单位]
// @return 目标位置 [指令单位]
static LONG PosToLong(double pos)
{
    double p = (pos >= 0.0) ? (pos + 0.5) : (pos - 0.5);
    if (p >  2000000000.0) p =  2000000000.0;
    if (p < -2000000000.0) p = -2000000000.0;
    return (LONG)p;
}

// 驱动侧 CiA402 模式号: CSV(9) / CST(10) / CSP(8)
// @param driveMode SpeedTestSequencer::DriveMode
// @return 6060h 模式号
static SHORT DriveModeCode(uint8_t driveMode)
{
    if (driveMode == SpeedTestSequencer::DRIVE_CST) {
        return 10;
    }
    if (driveMode == SpeedTestSequencer::DRIVE_CSP) {
        return 8;
    }
    return 9;
}

// 平台宏 → 伺服 Params (XAE/PLC 可在数据区覆盖)
// @param idx 0 = Servo0, 1 = Servo1
// @param s   该伺服
static void FillServoParams(int idx, ServoIO* s)
{
	if (s == NULL) {
		return;
	}
	if (idx == 0) {
		s->Params.EncCntPerRev = WASR_S0_ENC_CNT_PER_REV;
		s->Params.GearNum      = WASR_S0_GEAR_NUM;
		s->Params.GearDen      = WASR_S0_GEAR_DEN;
		s->Params.InertiaBase  = WASR_S0_INERTIA_BASE;
		s->Params.RatedTorque  = WASR_S0_RATED_TORQUE;
	} else {
		s->Params.EncCntPerRev = WASR_S1_ENC_CNT_PER_REV;
		s->Params.GearNum      = WASR_S1_GEAR_NUM;
		s->Params.GearDen      = WASR_S1_GEAR_DEN;
		s->Params.InertiaBase  = WASR_S1_INERTIA_BASE;
		s->Params.RatedTorque  = WASR_S1_RATED_TORQUE;
	}
}

// 按驱动侧序号设置 DriveSide / LoadSide 指针
// @param servos  双伺服结构
// @param driveNo 0 = Servo0 驱动, 1 = Servo1 驱动
static void ApplyDriveSideRoles(WASR_TCServos* servos, unsigned char driveNo)
{
	if (servos == NULL) {
		return;
	}
	if (driveNo == 1) {
		servos->DriveSide = &servos->Servo1;
		servos->LoadSide  = &servos->Servo0;
	} else {
		servos->DriveSide = &servos->Servo0;
		servos->LoadSide  = &servos->Servo1;
	}
}

// 下发电子齿轮比 6091:01h (Motor_revolutions) / 6091:02h (Shaft_revolutions)
// 必须与该伺服 Params 一致, 否则 [rpm] 换算与高速时的 60FFh/606Ch 都会出错
// @param s 该伺服
static void ApplyGearRatioOutputs(ServoIO* s)
{
	if (s == NULL) {
		return;
	}
	// 0 非法
	ULONG gearNum = s->Params.GearNum;
	ULONG gearDen = s->Params.GearDen;
	if (gearNum == 0) gearNum = 1;
	if (gearDen == 0) gearDen = 1;
	s->Outputs->Motor_revolutions = gearNum;
	s->Outputs->Shaft_revolutions = gearDen;
}

