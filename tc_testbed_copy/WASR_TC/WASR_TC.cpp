///////////////////////////////////////////////////////////////////////////////
// 驱动侧输出: CSV 写速度指令 (60FFh), CST 写转矩指令 (6071h),
//              CSP 写目标位置 (607Ah)
// @param d       驱动侧伺服
// @param spdCmd  速度指令 [rpm]
// @param opDrive 是否已 Operation Enabled (CSV/CST 未使能时输出 0)
///////////////////////////////////////////////////////////////////////////////
void CWASR_TC::DriveOutput_Run(ServoIO* d, float spdCmd, bool opDrive)
{
	if (d == NULL) {
		return;
	}

	if (m_testSeq.driveMode == SpeedTestSequencer::DRIVE_CSP) {
		// CSP: 只写目标位置, 速度/转矩清 0
		// 目标位置一直就是序列器给的值 (原点/原点+波形), 不管驱动器是否已使能:
		// 未使能时 607Ah 不动作, 但波形上不会出现"先跟实际位置、使能后再跳到原点"
		// 的指令突变 (使能过程约 10 ms, 之前会把 6064h 写进 607Ah 造成假跳变)
		d->Outputs->Target_position = PosToLong(m_testSeq.posCmdOut);
		d->Outputs->Target_velocity = 0;
		d->Outputs->Target_torque   = 0;
		d->Status.TorCmd_PcSend     = 0.0f;
	} else if (m_testSeq.driveMode == SpeedTestSequencer::DRIVE_CST) {
		// CST: 速度指令清 0, 转矩来自上位机速度环
		float torCmd = opDrive ? m_testSeq.torCmdOut : 0.0f;
		if (torCmd >  (float)WASR_TC_TORLIM) torCmd =  (float)WASR_TC_TORLIM;
		if (torCmd < -(float)WASR_TC_TORLIM) torCmd = -(float)WASR_TC_TORLIM;
		// 实际写进 6071h 的值 (SHORT)
		SHORT torOut = (SHORT)torCmd;
		d->Outputs->Target_velocity = 0;
		d->Outputs->Target_torque   = torOut;
		d->Status.TorCmd_PcSend     = (float)torOut;
	} else {
		// CSV: 伺服自带速度环, 转矩指令清 0
		d->Outputs->Target_velocity = (LONG)(spdCmd / m_speedScale);
		d->Outputs->Target_torque   = 0;
		d->Status.TorCmd_PcSend     = 0.0f;
	}

	// 速度指令回读 (Manual 时上位机写入, 其余实验由序列器给)
	d->Status.SpdCmd = spdCmd;
}

///////////////////////////////////////////////////////////////////////////////
// 单侧 CiA402 状态机: 0x06 → 0x07 → 0x0F
// @param s      该侧伺服
// @param enable 模块级 Enable
// @param rising Enable 上升沿 (用于故障复位)
// @param step   该侧步号 (0..3)
// @param mode   9 = CSV, 10 = CST
// @return true = 已 Operation Enabled
///////////////////////////////////////////////////////////////////////////////
static bool CiA402_Step(ServoIO* s, bool enable, bool rising, uint8_t& step, SHORT mode)
{
	if (s == NULL) {
		return false;
	}
	USHORT sw = s->Inputs->Status_word;
	uint8_t swReady = (sw & 0x0001) ? 1 : 0;
	uint8_t swSwOn  = (sw & 0x0002) ? 1 : 0;
	uint8_t swOpEn  = (sw & 0x0004) ? 1 : 0;
	uint8_t swFault = (sw & 0x0008) ? 1 : 0;

	// 目标模式每拍写入
	s->Outputs->Modes_of_operation = (char)mode;

	// 上升沿且有故障: 发故障复位 (0x0080), 不启动
	if (rising && swFault) {
		s->Outputs->Controlword = 0x0080;
		step = 0;
		return false;
	}

	// Enable = 0: 禁用
	if (!enable) {
		s->Outputs->Controlword = 0x0000;
		step = 0;
		return false;
	}

	// 故障: 立即停止, 不自动复位
	if (swFault) {
		s->Outputs->Controlword = 0x0000;
		step = 0;
		return false;
	}

	// 状态切换: 0x06 -> 0x07 -> 0x0F
	if (step == 0) {
		s->Outputs->Controlword = 0x0006;
		if (swReady) step = 1;
	} else if (step == 1) {
		s->Outputs->Controlword = 0x0007;
		if (swReady && swSwOn) step = 2;
	} else if (step == 2) {
		s->Outputs->Controlword = 0x000F;
		if (swReady && swSwOn && swOpEn) step = 3;
	}

	return (step == 3);
}

///////////////////////////////////////////////////////////////////////////////
// 双侧 CiA402 推进 (同一 Enable 同时启动/停止)
//   DriveSide: 转矩扫频 (含停机斜坡) → CST(10), 位置环波形 (含停机淡出) → CSP(8),
//              其余 → CSV(9)
//   LoadSide : 恒 CST(10)
// @param opDrive/opLoad 输出两侧是否 Operation Enabled
///////////////////////////////////////////////////////////////////////////////
void CWASR_TC::CiA402_Update(bool& opDrive, bool& opLoad)
{
	// Enable 上升沿 (两侧共用)
	bool rising = (m_prevEnable == 0 && m_Status.Enable != 0);
	m_prevEnable = m_Status.Enable;

	ServoIO* d = m_Servos.DriveSide;
	if (d == NULL) {
		d = &m_Servos.Servo0;
		m_Servos.DriveSide = d;
	}
	SHORT modeDrive = DriveModeCode(m_testSeq.driveMode);
	opDrive = CiA402_Step(d, m_Status.Enable != 0, rising, m_cia402Step, modeDrive);

	ServoIO* ld = m_Servos.LoadSide;
	if (ld == NULL) {
		ld = (d == &m_Servos.Servo0) ? &m_Servos.Servo1 : &m_Servos.Servo0;
		m_Servos.LoadSide = ld;
	}
	opLoad = CiA402_Step(ld, m_Status.Enable != 0, rising, m_cia402StepLoad, 10);
}

