///////////////////////////////////////////////////////////////////////////////
// 驱动轴输出: CSV 写速度指令 (60FFh), CST 写转矩指令 (6071h),
//              CSP 写目标位置 (607Ah)
// @param pServo    该轴伺服
// @param nAxis     驱动轴序号 (0..3), 决定取 posCmdOut[nAxis]
// @param fSpdCmd   速度指令 [rpm]
// @param bOpEnabled 该轴是否已 Operation Enabled (CSV/CST 未使能时输出 0)
///////////////////////////////////////////////////////////////////////////////
void CWASR_TC::DriveOutput_Run(ServoIO* pServo, int nAxis, float fSpdCmd, bool bOpEnabled)
{
	if (pServo == NULL) {
		return;
	}
	int nSlot = SlotOfServo(m_apServo, pServo);

	if (m_testSeq.driveMode == SpeedTestSequencer::DRIVE_CSP) {
		// CSP: 只写目标位置, 速度/转矩清 0
		// 目标位置一直就是序列器给的值, 不管驱动器是否已使能:
		// 未使能时 607Ah 不动作, 但波形上不会出现"先跟实际位置、使能后再跳到原点"
		// 的指令突变 (使能过程约 10 ms, 之前会把 6064h 写进 607Ah 造成假跳变)
		double fPos = m_testSeq.posCmdOut[0];
		if ((nAxis >= 0) && (nAxis < SITE_AXIS_MAX)) {
			fPos = m_testSeq.posCmdOut[nAxis];
		}
		pServo->Outputs->Target_position = PosToLong(fPos);
		pServo->Outputs->Target_velocity = 0;
		pServo->Outputs->Target_torque   = 0;
		// 60B1h 速度前馈 [指令单位/s]: 与 607Ah 同拍下发。
		// 驱动器在「位置环之后、速度环之前」把它加进速度指令 (IEC 61800-7-201 图 74),
		// 所以位置环只修残差, 稳态滞后不需要再靠指令超前补偿。
		// 序列器只在 CAM_RUN 期间给非零值, 其余状态每拍清零 —— 残留 = 电机自己转。
		pServo->Outputs->Velocity_offset =
			PosToLong(((nAxis >= 0) && (nAxis < SITE_AXIS_MAX)) ? m_testSeq.feedVelFf[nAxis] : 0.0);
		// 60B2h 转矩前馈 [0.1% 额定]: 同样与 607Ah 同拍下发。
		// 序列器按「总惯量 × 凸轮加速度」算好 —— 加速段给正、减速段给负、同步段为 0，
		// 所以它只修加减速过渡，不参与稳态精度。非本文实验/非 CAM_RUN 时序列器已是 0。
		// 外面再夹一次 SHORT 范围：序列器已按 fTorFfGain 缩放过，这里只防溢出。
		double fTorFf = ((nAxis >= 0) && (nAxis < SITE_AXIS_MAX)) ? m_testSeq.feedTorFf[nAxis] : 0.0;
		if (fTorFf >  32767.0) { fTorFf =  32767.0; }
		if (fTorFf < -32768.0) { fTorFf = -32768.0; }
		pServo->Outputs->Torque_offset = (SHORT)fTorFf;
		pServo->Status.TorCmd_PcSend     = 0.0f;
	} else if (m_testSeq.driveMode == SpeedTestSequencer::DRIVE_CST) {
		// CST: 速度指令清 0, 转矩来自上位机速度环 (转矩扫频是单轴实验, 只轴0给)
		float torCmd = (bOpEnabled && (nAxis == 0)) ? m_testSeq.torCmdOut : 0.0f;
		if (torCmd >  (float)WASR_TC_TORLIM) torCmd =  (float)WASR_TC_TORLIM;
		if (torCmd < -(float)WASR_TC_TORLIM) torCmd = -(float)WASR_TC_TORLIM;
		// 实际写进 6071h 的值 (SHORT)
		SHORT torOut = (SHORT)torCmd;
		pServo->Outputs->Target_velocity = 0;
		pServo->Outputs->Target_torque   = torOut;
		pServo->Outputs->Velocity_offset = 0;   // 前馈只在 CSP 用, 换模式必须清掉
		pServo->Outputs->Torque_offset   = 0;   // 同上: 60B2 残留会一直往转矩环加偏置
		pServo->Status.TorCmd_PcSend     = (float)torOut;
	} else {
		// CSV: 伺服自带速度环, 转矩指令清 0; 只有轴0 跟速度曲线, 其余轴给 0
		float fCmd = (nAxis == 0) ? fSpdCmd : 0.0f;
		pServo->Outputs->Target_velocity = (LONG)(fCmd / m_speedScaleServo[nSlot]);
		pServo->Outputs->Target_torque   = 0;
		pServo->Outputs->Velocity_offset = 0;   // 前馈只在 CSP 用, 换模式必须清掉
		pServo->Outputs->Torque_offset   = 0;   // 同上
		pServo->Status.TorCmd_PcSend     = 0.0f;
	}

	// 速度指令回读 (Manual 时上位机写入, 其余实验由序列器给)
	pServo->Status.SpdCmd = (nAxis == 0) ? fSpdCmd : 0.0f;
}

///////////////////////////////////////////////////////////////////////////////
// 单侧 CiA402 状态机: 0x06 → 0x07 → 0x0F
// @param s      该侧伺服
// @param enable 模块级 Enable
// @param rising Enable 上升沿 (用于故障复位)
// @param step   该侧步号 (0..3)
// @param mode   9 = CSV, 10 = CST
// @return true = 已 Operation Enabled
///////////////////////////////////////////////////////////////////////////////
static bool CiA402_Step(ServoIO* s, bool enable, bool rising, uint8_t& step, SHORT mode)
{
	if (s == NULL) {
		return false;
	}
	USHORT sw = s->Inputs->Status_word;
	uint8_t swReady = (sw & 0x0001) ? 1 : 0;
	uint8_t swSwOn  = (sw & 0x0002) ? 1 : 0;
	uint8_t swOpEn  = (sw & 0x0004) ? 1 : 0;
	uint8_t swFault = (sw & 0x0008) ? 1 : 0;

	// 目标模式每拍写入
	s->Outputs->Modes_of_operation = (char)mode;

	// 上升沿且有故障: 发故障复位 (0x0080), 不启动
	if (rising && swFault) {
		s->Outputs->Controlword = 0x0080;
		step = 0;
		return false;
	}

	// Enable = 0: 禁用
	if (!enable) {
		s->Outputs->Controlword = 0x0000;
		step = 0;
		return false;
	}

	// 故障: 立即停止, 不自动复位
	if (swFault) {
		s->Outputs->Controlword = 0x0000;
		step = 0;
		return false;
	}

	// 状态切换: 0x06 -> 0x07 -> 0x0F
	if (step == 0) {
		s->Outputs->Controlword = 0x0006;
		if (swReady) step = 1;
	} else if (step == 1) {
		s->Outputs->Controlword = 0x0007;
		if (swReady && swSwOn) step = 2;
	} else if (step == 2) {
		s->Outputs->Controlword = 0x000F;
		if (swReady && swSwOn && swOpEn) step = 3;
	}

	return (step == 3);
}

///////////////////////////////////////////////////////////////////////////////
// 各槽位 CiA402 推进 (同一 Enable 同时启动/停止, 每槽位独立步号)
//   驱动轴: 转矩扫频 (含停机斜坡) → CST(10), 位置环波形/送纸凸轮 → CSP(8),
//           其余 → CSV(9); 轴1..3 固定 CSP (只跑凸轮)
//   负载轴: 恒 CST(10), 只有 g_cfgFeed.bLoadSideEnable 打开才使能
//   角色 NONE 的槽位: Controlword 强制 0, 不参与状态机
///////////////////////////////////////////////////////////////////////////////
void CWASR_TC::CiA402_Update()
{
	// Enable 上升沿 (所有槽位共用)
	bool rising = (m_prevEnable == 0 && m_Status.Enable != 0);
	m_prevEnable = m_Status.Enable;

	SHORT modeDrive = DriveModeCode(m_testSeq.driveMode);

	// 本实验用到的驱动轴数: 送纸凸轮按站点表 (1..4), 其余实验只用轴0
	int nActiveAxes = 1;
	if (m_testSeq.mode == SpeedTestSequencer::FEED_CAM_TEST) {
		nActiveAxes = (int)m_nDriveAxisCount;
		if (nActiveAxes < 1) {
			nActiveAxes = 1;
		}
	}

	// 驱动轴
	for (int a = 0; a < SITE_AXIS_MAX; a++) {
		ServoIO* pServo = m_apDrive[a];
		if (pServo == NULL) {
			m_abOpDrive[a] = false;
			continue;
		}
		int nSlot = SlotOfServo(m_apServo, pServo);
		bool bEnable = (m_Status.Enable != 0) && (a < nActiveAxes);
		// 轴0 跟实验模式, 轴1..3 只跑凸轮 = 固定 CSP
		SHORT mode = (a == 0) ? modeDrive : DriveModeCode(SpeedTestSequencer::DRIVE_CSP);
		m_abOpDrive[a] = CiA402_Step(pServo, bEnable, rising, m_aucCia402Step[nSlot], mode);
	}

	// 负载轴 (恒 CST; 开关关闭时禁用, 但 Controlword 会清 0 不留残留)
	{
		bool bLoadEnable = (m_Status.Enable != 0) && g_cfgFeed.bLoadSideEnable;
		for (int a = 0; a < SITE_AXIS_MAX; a++) {
			ServoIO* pServo = m_apLoad[a];
			if (pServo == NULL) {
				m_abOpLoad[a] = false;
				continue;
			}
			int nSlot = SlotOfServo(m_apServo, pServo);
			m_abOpLoad[a] = CiA402_Step(pServo, bLoadEnable, rising, m_aucCia402Step[nSlot], 10);
		}
	}

	// 没接设备的槽位: 输出必须保持 0 (未链接槽位输入恒 0, 不能留上次的 Controlword)
	for (int i = 0; i < SITE_SLOT_MAX; i++) {
		if (m_aucRole[i] == SLOT_ROLE_NONE) {
			m_apServo[i]->Outputs->Controlword = 0;
			m_aucCia402Step[i] = 0;
		}
	}
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CWASR_TC::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID;
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

